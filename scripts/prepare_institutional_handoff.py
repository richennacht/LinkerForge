#!/usr/bin/env python3
"""Create a checksummed, non-submitted SLURM handoff for ColabFold/OpenMM.

Credentials are never read or bundled.  The package remains execution-blocked
until an institution supplies and approves a completed profile.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import re
import shutil
import subprocess
import zipfile
from datetime import datetime, timezone
from pathlib import Path


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def git_value(repo: Path, *args: str) -> str:
    try:
        return subprocess.check_output(["git", *args], cwd=repo, text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return "not-available"


def require_shell_token(value: str, field: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9_.:/+-]+", value):
        raise ValueError(f"Unsafe or incomplete {field}: {value!r}")
    return value


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fasta", type=Path, required=True)
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    if args.output_dir.exists():
        raise SystemExit("Handoff output already exists; refusing to overwrite it")
    profile = json.loads(args.profile.read_text(encoding="utf-8"))
    required = ["institution", "partition", "account", "gpu_resource", "time_limit", "colabfold_command"]
    missing = [field for field in required if not profile.get(field) or str(profile[field]).startswith("REPLACE_")]
    if missing:
        raise SystemExit(f"Institutional profile is incomplete: {', '.join(missing)}")
    for field in required:
        require_shell_token(str(profile[field]), field)

    args.output_dir.mkdir(parents=True)
    shutil.copy2(args.fasta, args.output_dir / "input.fasta")
    shutil.copy2(args.profile, args.output_dir / "institution-profile.json")
    repo = Path(__file__).resolve().parents[1]
    script = f"""#!/usr/bin/env bash
# Generated by LinkerForge. Review under institutional policy before sbatch.
#SBATCH --job-name=linkerforge-fold
#SBATCH --partition={profile['partition']}
#SBATCH --account={profile['account']}
#SBATCH --gres={profile['gpu_resource']}
#SBATCH --time={profile['time_limit']}
#SBATCH --cpus-per-task={int(profile.get('cpus_per_task', 8))}
#SBATCH --mem={profile.get('memory', '64G')}
#SBATCH --output=slurm-%j.out
set -euo pipefail
test "$(sha256sum input.fasta | cut -d' ' -f1)" = "{sha256(args.fasta)}"
mkdir -p prediction
{profile['colabfold_command']} input.fasta prediction --use-fast-kernels
sha256sum input.fasta prediction/* > output-checksums.sha256
touch COMPLETE
"""
    (args.output_dir / "run.sbatch").write_text(script, encoding="utf-8", newline="\n")
    commit_sha = git_value(repo, "rev-parse", "HEAD")
    worktree_modified = bool(git_value(repo, "status", "--porcelain"))
    manifest = {
        "schema_version": "linkerforge.institutional-handoff.v1",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "status": "ready_for_institutional_review" if profile.get("approved") else "blocked_pending_institutional_approval",
        "institution": profile["institution"],
        "input_fasta_sha256": sha256(args.output_dir / "input.fasta"),
        "source_ids": [
            f"fasta-sha256:{sha256(args.output_dir / 'input.fasta')}",
            f"institution:{profile['institution']}",
        ],
        "profile_sha256": sha256(args.output_dir / "institution-profile.json"),
        "sbatch_sha256": sha256(args.output_dir / "run.sbatch"),
        "linkerforge_commit": commit_sha,
        "working_tree": "modified" if worktree_modified else "clean",
        "provenance": {
            "commit_sha": commit_sha,
            "worktree_modified": worktree_modified,
            "config_sha256": sha256(args.output_dir / "institution-profile.json"),
            "versions": {"python": platform.python_version(), "handoff_builder": "1.0.0"},
        },
        "evidence_quality": "unsubmitted_institutional_execution_handoff",
        "credentials_included": False,
        "submission_performed": False,
        "claim_boundary": "This package prepares but does not authorize or submit institutional compute.",
    }
    (args.output_dir / "handoff-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    checksums = "".join(f"{sha256(path)}  {path.name}\n" for path in sorted(args.output_dir.iterdir()) if path.is_file())
    (args.output_dir / "checksums.sha256").write_text(checksums, encoding="utf-8")
    archive = args.output_dir.with_suffix(".zip")
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for path in sorted(args.output_dir.iterdir()):
            if path.is_file():
                bundle.write(path, path.name)


if __name__ == "__main__":
    main()
